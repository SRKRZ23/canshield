#!/usr/bin/env python3
"""Train a differentiable logic-gate network (Petersen et al., NeurIPS 2022 style) on CANSHIELD
binary features, harden it to a pure Boolean circuit, export C, and report honest metrics.
Training uses unique (pattern, label) pairs weighted by their counts, so it runs in seconds on CPU.
usage: python3 scripts/train_lgn.py [--layers 3 --width 96 --groups 16 --seed 0 --target_fpr 0.002]"""
import argparse, json, os, sys
import numpy as np, torch, torch.nn as nn
sys.path.insert(0, os.path.dirname(__file__))
from data import manifest, REC, NFEAT, NAMES, ROOT

# the 16 two-input Boolean functions as differentiable relaxations (a, b in [0,1])
def ops(a, b):
    ab = a * b
    return torch.stack([torch.zeros_like(a), ab, a - ab, a, b - ab, b, a + b - 2 * ab, a + b - ab,
                        1 - (a + b - ab), 1 - (a + b - 2 * ab), 1 - b, 1 - b + ab, 1 - a, 1 - a + ab,
                        1 - ab, torch.ones_like(a)], -1)
C_OPS = ["0", "a&b", "a&~b", "a", "~a&b", "b", "a^b", "a|b", "~(a|b)", "~(a^b)", "~b", "a|~b", "~a", "~a|b",
         "~(a&b)", "1"]
def hard_op(k, a, b):
    a = a.astype(bool); b = b.astype(bool)
    return [np.zeros_like(a), a & b, a & ~b, a, ~a & b, b, a ^ b, a | b, ~(a | b), ~(a ^ b), ~b, a | ~b, ~a,
            ~a | b, ~(a & b), np.ones_like(a)][k].astype(np.uint8)

class LGN(nn.Module):
    def __init__(self, nin, layers, width, groups, seed):
        super().__init__()
        g = torch.Generator().manual_seed(seed)
        self.wires, self.logits = [], nn.ParameterList()
        prev = nin
        for li in range(layers):
            a = torch.randint(0, prev, (width,), generator=g); b = torch.randint(0, prev, (width,), generator=g)
            if li == 0:   # guarantee every input feature reaches at least two gates
                a[:prev] = torch.randperm(prev, generator=g); b[:prev] = torch.randperm(prev, generator=g)
            self.wires.append((a, b))
            w = torch.zeros(width, 16); w[:, 3] = 2.0; w[:, 5] = 1.0       # start near pass-through
            self.logits.append(nn.Parameter(w + 0.1 * torch.randn(width, 16, generator=g)))
            prev = width
        self.groups, self.width = groups, width
        self.tau = nn.Parameter(torch.tensor(4.0))
    def forward(self, x):
        for (a, b), L in zip(self.wires, self.logits):
            x = (ops(x[:, a], x[:, b]) * torch.softmax(L, -1)).sum(-1)
        # output: first `groups` neurons of the last layer vote for "attack"
        return x[:, :self.groups].sum(-1) / self.tau - self.groups / (2 * self.tau)
    def harden(self):
        return [(a.numpy(), b.numpy(), L.argmax(-1).numpy()) for (a, b), L in zip(self.wires, self.logits)]

def run_hard(circ, X, groups):
    x = X
    for a, b, k in circ:
        x = np.stack([hard_op(int(k[j]), x[:, a[j]], x[:, b[j]]) for j in range(len(k))], 1)
    return x[:, :groups].sum(1)                     # attack votes 0..groups

def unique_split(split, balanced=False):
    feats, labs, cnt = [], [], []
    agg = {}
    for e in manifest():
        if e['split'] != split: continue
        r = np.fromfile(e['path'], dtype=REC)
        k = (r['feat'] << np.uint64(1)) | r['label'].astype(np.uint64)
        u, c = np.unique(k, return_counts=True)
        c = c.astype(np.float64)
        if balanced:   # every capture contributes equal benign mass and equal attack mass
            pos = (u & np.uint64(1)) == 1
            if pos.any(): c[pos] = c[pos] / c[pos].sum() * 1e6
            c[~pos] = c[~pos] / c[~pos].sum() * 1e6
        for kk, cc in zip(u.tolist(), c.tolist()): agg[kk] = agg.get(kk, 0) + cc
    keys = np.array(list(agg.keys()), dtype=np.uint64); cnts = np.array(list(agg.values()), dtype=np.float64)
    feat = keys >> np.uint64(1); lab = (keys & np.uint64(1)).astype(np.uint8)
    X = ((feat[:, None] >> np.arange(NFEAT, dtype=np.uint64)) & 1).astype(np.uint8)
    return X, lab, cnts, feat

def export_c(circ, groups, thr, path, meta):
    L = [f"/* AUTO-GENERATED by scripts/train_lgn.py — CANSHIELD hardened logic-gate classifier.",
         f" * {meta}",
         " * Pure Boolean circuit: AND/OR/XOR/NOT on bits, fixed gate count, no branches, no floats,",
         " * no memory allocation -> constant execution time per frame. SPDX-License-Identifier: Apache-2.0 */",
         "#include <stdint.h>", f"#define CS_MODEL_GROUPS {groups}", f"#define CS_MODEL_THRESHOLD {thr}",
         f"const int cs_model_threshold = {thr};",
         "/* returns number of 'attack' votes (0..CS_MODEL_GROUPS); attack if >= CS_MODEL_THRESHOLD */",
         "int cs_model_votes(uint64_t feat) {"]
    L.append("    uint8_t i[%d];" % NFEAT)
    L.append("    for (int k = 0; k < %d; k++) i[k] = (uint8_t)((feat >> k) & 1u);" % NFEAT)
    prev = "i"; ng = 0
    for li, (a, b, k) in enumerate(circ):
        cur = f"l{li}"; L.append(f"    uint8_t {cur}[{len(k)}];")
        for j in range(len(k)):
            ea, eb = f"{prev}[{a[j]}]", f"{prev}[{b[j]}]"
            expr = C_OPS[int(k[j])].replace("a", "A").replace("b", "B").replace("A", ea).replace("B", eb)
            L.append(f"    {cur}[{j}] = (uint8_t)(({expr}) & 1u);"); ng += 1
        prev = cur
    L.append("    int v = 0;")
    L.append(f"    for (int k = 0; k < {groups}; k++) v += {prev}[k];")
    L.append("    return v;\n}")
    L.append(f"/* gates: {ng} */")
    open(path, 'w').write("\n".join(L) + "\n")
    return ng

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--layers', type=int, default=4); ap.add_argument('--width', type=int, default=128)
    ap.add_argument('--groups', type=int, default=16); ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--epochs', type=int, default=2000); ap.add_argument('--target_fpr', type=float, default=0.002)
    ap.add_argument('--pos_weight', type=float, default=1.0); ap.add_argument('--lr', type=float, default=0.2)
    A = ap.parse_args()
    torch.manual_seed(A.seed); torch.set_num_threads(4)
    X, y, c, feat = unique_split('train')                   # true frequencies (for FPR/threshold)
    _, yb, cb, featb = unique_split('train', balanced=True)  # per-capture balanced (for the loss)
    cbal = dict(zip(((featb << np.uint64(1)) | yb.astype(np.uint64)).tolist(), cb.tolist()))
    wb = np.array([cbal[k] for k in ((feat << np.uint64(1)) | y.astype(np.uint64)).tolist()])
    w = np.where(y == 1, wb / wb[y == 1].sum() * A.pos_weight, wb / wb[y == 0].sum())
    Xt = torch.tensor(X, dtype=torch.float32); yt = torch.tensor(y, dtype=torch.float32); wt = torch.tensor(w / w.sum(), dtype=torch.float32)
    m = LGN(NFEAT, A.layers, A.width, A.groups, A.seed)
    opt = torch.optim.Adam(m.parameters(), lr=A.lr)
    for ep in range(A.epochs):
        opt.zero_grad()
        loss = (nn.functional.binary_cross_entropy_with_logits(m(Xt), yt, reduction='none') * wt).sum()
        loss.backward(); opt.step()
    circ = m.harden()
    votes = run_hard(circ, X, A.groups)
    # choose the lowest threshold whose weighted benign FPR on TRAIN <= target
    ben = y == 0; best = A.groups + 1
    for t in range(A.groups + 1):
        fpr = c[ben & (votes >= t)].sum() / c[ben].sum()
        if fpr <= A.target_fpr: best = t; break
    tr_fpr = c[ben & (votes >= best)].sum() / c[ben].sum(); tr_rec = c[(~ben) & (votes >= best)].sum() / c[~ben].sum()
    print(f"seed {A.seed}: loss {loss.item():.4f}  threshold {best}/{A.groups}  train recall {tr_rec:.3f}  train FPR {tr_fpr:.5f}")
    out = os.path.join(ROOT, 'build'); os.makedirs(out, exist_ok=True)
    meta = f"layers={A.layers} width={A.width} groups={A.groups} seed={A.seed} threshold={best} train_recall={tr_rec:.4f} train_fpr={tr_fpr:.5f}"
    ng = export_c(circ, A.groups, best, os.path.join(out, 'cs_model.c'), meta)
    np.save(os.path.join(out, 'circuit.npy'), np.array(circ, dtype=object), allow_pickle=True)
    # lookup table of the hardened model over every TRAIN+TEST pattern for the C parity test
    Xa, ya, ca, fa = unique_split('test')
    allf = np.unique(np.concatenate([feat, fa])); Xall = ((allf[:, None] >> np.arange(NFEAT, dtype=np.uint64)) & 1).astype(np.uint8)
    np.savez(os.path.join(out, 'parity.npz'), feat=allf, votes=run_hard(circ, Xall, A.groups))
    json.dump(dict(vars(A), threshold=int(best), gates=ng, train_recall=tr_rec, train_fpr=tr_fpr), open(os.path.join(out, 'model_meta.json'), 'w'), indent=1)
    print(f"exported build/cs_model.c ({ng} gates)")

if __name__ == '__main__':
    main()
